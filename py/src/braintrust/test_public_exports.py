def test_top_level_exports_match_snapshot():
    result = subprocess.run(
        [
            sys.executable,
            "-c",
            "import braintrust, json; print(json.dumps(sorted(name for name in vars(braintrust) if not name.startswith('_'))))",
        ],
        check=True,
        capture_output=True,
        text=True,
    )
    actual = json.loads(result.stdout)
    assert actual == _EXPECTED_EXPORTS
